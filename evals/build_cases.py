"""Build the 20-case drift evaluation set from the real r1 sample.

Expected paths are declared by hand, not generated by the implementation,
so the evaluation cannot agree with itself by construction.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASELINE = (ROOT / "samples/frr/r1.conf").read_text(encoding="utf-8")
OUT = ROOT / "evals/cases.json"

CASES: list[dict] = []


def case(case_id: str, description: str, current: str, expected: list[str],
         items: list[dict] | None = None) -> None:
    entry = {"id": case_id, "description": description, "current": current, "expected_paths": expected}
    if items:
        entry["expected_items"] = items
    CASES.append(entry)


def replace(text: str, old: str, new: str) -> str:
    assert old in text, old
    return text.replace(old, new, 1)


case("D01", "无变化", BASELINE, [])
case("D02", "互联接口 cost 10 → 20",
     replace(BASELINE, " ip ospf cost 10", " ip ospf cost 20"), ["interface.eth2.ospf.cost"],
     [{"path": "interface.eth2.ospf.cost", "kind": "changed", "old": 10, "new": 20,
       "old_lines": [14], "new_lines": [14]}])
case("D03", "互联接口删除 cost",
     replace(BASELINE, " ip ospf cost 10\n", ""), ["interface.eth2.ospf.cost"])
case("D04", "单条 network 的 area 变更",
     replace(BASELINE, "network 10.12.0.0/30 area 0.0.0.0", "network 10.12.0.0/30 area 0.0.0.1"),
     ["ospf.networks"],
     [{"path": "ospf.networks", "kind": "changed",
       "old": [{"prefix": "10.101.0.0/30", "area": "0.0.0.0"},
               {"prefix": "10.12.0.0/30", "area": "0.0.0.0"},
               {"prefix": "10.13.0.0/30", "area": "0.0.0.0"},
               {"prefix": "10.255.1.1/32", "area": "0.0.0.0"}],
       "new": [{"prefix": "10.101.0.0/30", "area": "0.0.0.0"},
               {"prefix": "10.12.0.0/30", "area": "0.0.0.1"},
               {"prefix": "10.13.0.0/30", "area": "0.0.0.0"},
               {"prefix": "10.255.1.1/32", "area": "0.0.0.0"}]}])
case("D05", "删除一条 network 宣告",
     replace(BASELINE, " network 10.13.0.0/30 area 0.0.0.0\n", ""), ["ospf.networks"])
case("D06", "新增一条 network 宣告",
     replace(BASELINE, " network 10.13.0.0/30 area 0.0.0.0\n",
             " network 10.13.0.0/30 area 0.0.0.0\n network 10.77.0.0/30 area 0.0.0.0\n"),
     ["ospf.networks"])
case("D07", "移除 eth1 的 passive",
     replace(BASELINE, " passive-interface eth1\n", ""), ["ospf.passive_interfaces"])
case("D08", "移除 lo 的 passive",
     replace(BASELINE, " passive-interface lo\n", ""), ["ospf.passive_interfaces"])
case("D09", "新增 eth2 为 passive",
     replace(BASELINE, " passive-interface eth1\n", " passive-interface eth1\n passive-interface eth2\n"),
     ["ospf.passive_interfaces"])
case("D10", "接口描述变更",
     replace(BASELINE, " description r1-to-r2-primary", " description core-uplink"),
     ["interface.eth2.description"])
case("D11", "接口被 shutdown",
     replace(BASELINE, " ip address 10.12.0.1/30", " ip address 10.12.0.1/30\n shutdown"),
     ["interface.eth2.shutdown"])
case("D12", "接口地址变更",
     replace(BASELINE, " ip address 10.12.0.1/30", " ip address 10.12.0.5/30"),
     ["interface.eth2.addresses"])
case("D13", "删除 eth3 接口整段",
     replace(BASELINE, "interface eth3\n description r1-to-r3-backup\n ip address 10.13.0.1/30\n ip ospf network point-to-point\n ip ospf cost 50\n!\n", ""),
     ["interface.eth3"],
     [{"path": "interface.eth3", "kind": "removed", "old_not_null": True, "new": None}])
case("D14", "新增 eth9 接口",
     BASELINE + "\ninterface eth9\n description spare\n ip address 10.99.0.1/30\n!\n",
     ["interface.eth9"])
case("D15", "router-id 变更",
     replace(BASELINE, " ospf router-id 10.255.1.1", " ospf router-id 10.255.1.9"),
     ["ospf.router_id"])
case("D16", "hostname 变更",
     replace(BASELINE, "hostname r1", "hostname r1-renamed"), ["hostname"],
     [{"path": "hostname", "kind": "changed", "old": "r1", "new": "r1-renamed",
       "old_lines": [2], "new_lines": [2]}])
case("D17", "新增 default-information originate",
     replace(BASELINE, " passive-interface eth1\n", " passive-interface eth1\n default-information originate\n"),
     ["ospf.default_information"])
case("D18", "移除 point-to-point 类型",
     replace(BASELINE, " ip ospf network point-to-point\n ip ospf cost 10", " ip ospf cost 10"),
     ["interface.eth2.ospf.network_type"])
case("D19", "Loopback 地址变更",
     replace(BASELINE, " ip address 10.255.1.1/32", " ip address 10.255.1.9/32"),
     ["interface.lo.addresses"])
case("D20", "三处同时变更（cost / passive / network）",
     replace(replace(replace(BASELINE, " ip ospf cost 10", " ip ospf cost 30"),
                     " passive-interface lo\n", ""),
             " network 10.13.0.0/30 area 0.0.0.0\n", ""),
     ["interface.eth2.ospf.cost", "ospf.passive_interfaces", "ospf.networks"],
     [{"path": "interface.eth2.ospf.cost", "kind": "changed", "old": 10, "new": 30,
       "old_lines": [14], "new_lines": [14]},
      {"path": "ospf.passive_interfaces", "kind": "changed", "old": ["eth1", "lo"], "new": ["eth1"]},
      {"path": "ospf.networks", "kind": "changed"}])


def main() -> None:
    payload = {"schema_version": 1, "baseline": BASELINE, "cases": CASES}
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {len(CASES)} cases -> {OUT}")


if __name__ == "__main__":
    main()
